export function normalizePath(pathname: string) {
  let path = pathname || "/";
  if (path.length > 1 && path.endsWith("/")) {
    path = path.slice(0, -1);
  }
  if (path.endsWith("/index.md")) {
    path = path.slice(0, -"/index.md".length) || "/";
  } else if (path.endsWith(".md")) {
    path = path.slice(0, -3) || "/";
  }
  return path || "/";
}

export function hasMarkdown(pathname: string) {
  return normalizePath(pathname) in PAGES;
}

export function markdownFor(pathname: string) {
  return PAGES[normalizePath(pathname)] ?? null;
}

export function markdownTokens(body: string) {
  return Math.ceil(body.length / 4);
}
